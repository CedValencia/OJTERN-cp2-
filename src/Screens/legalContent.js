// Turns the plain text above into renderable blocks: meta / h2 / h3 / p / ul
export function parseLegalDoc(raw) {
  const lines = raw.split("\n").map((l) => l.trim());
  const blocks = [];
  for (const line of lines) {
    if (!line) continue;
    if (/^_{5,}$/.test(line)) continue;
    if (/^•\s*/.test(line)) {
      const text = line.replace(/^•\s*/, "");
      const last = blocks[blocks.length - 1];
      if (last && last.type === "ul") last.items.push(text);
      else blocks.push({ type: "ul", items: [text] });
      continue;
    }
    if (/^\d+\.\d+\s+\S/.test(line)) { blocks.push({ type: "h3", text: line }); continue; }
    if (/^\d+\.\s+\S/.test(line))     { blocks.push({ type: "h2", text: line }); continue; }
    if (/^(Effective Date|Version):/.test(line)) { blocks.push({ type: "meta", text: line }); continue; }
    blocks.push({ type: "p", text: line });
  }
  return blocks;
}